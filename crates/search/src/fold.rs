/// Letters that fold to more than one letter, or whose base is not a canonical decomposition.
fn special(c: char) -> Option<&'static str> {
    Some(match c {
        'ß' | 'ẞ' => "ss",
        'æ' => "ae",
        'œ' => "oe",
        'ø' => "o",
        'đ' | 'ð' => "d",
        'ł' => "l",
        'ħ' => "h",
        'ı' => "i",
        'þ' => "th",
        'ŀ' => "l",
        'ŧ' => "t",
        'ĳ' => "ij",
        'ﬁ' => "fi",
        'ﬂ' => "fl",
        'ﬀ' => "ff",
        'ς' => "σ",
        _ => return None,
    })
}

/// True for combining diacritical marks (dropped while folding).
fn is_mark(c: char) -> bool {
    matches!(c, '\u{0300}'..='\u{036F}' | '\u{1AB0}'..='\u{1AFF}' | '\u{1DC0}'..='\u{1DFF}' | '\u{20D0}'..='\u{20FF}' | '\u{FE20}'..='\u{FE2F}')
}

/// Appends the folded form of one (already lower-cased) char.
fn push_lower(c: char, out: &mut String) {
    if c.is_ascii() {
        out.push(c);
    } else if is_mark(c) {
    } else if let Some(s) = special(c) {
        out.push_str(s);
    } else if let Ok(i) = STRIP.binary_search_by_key(&c, |(k, _)| *k) {
        out.push(STRIP.get(i).map_or(c, |(_, b)| *b));
    } else {
        out.push(c);
    }
}

/// Appends the folded form of `c` to `out`.
pub fn fold_char_into(c: char, out: &mut String) {
    if c.is_ascii() {
        out.push(c.to_ascii_lowercase());
        return;
    }
    for l in c.to_lowercase() {
        push_lower(l, out);
    }
}

/// Appends the folded form of `text` to `out`.
pub fn fold_into(text: &str, out: &mut String) {
    for c in text.chars() {
        fold_char_into(c, out);
    }
}

/// The folded form of `text` (case and diacritics removed).
pub fn fold(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    fold_into(text, &mut out);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted() {
        assert!(STRIP.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn folds_case_and_diacritics() {
        assert_eq!(fold("Résumé"), "resume");
        assert_eq!(fold("RE\u{301}SUME\u{301}"), "resume");
        assert_eq!(fold("Straße"), "strasse");
        assert_eq!(fold("ŁÓDŹ"), "lodz");
        assert_eq!(fold("Ærøskøbing"), "aeroskobing");
        assert_eq!(fold("Ἀθῆναι"), "αθηναι");
        assert_eq!(fold("Tiếng Việt"), "tieng viet");
        assert_eq!(fold("İstanbul"), "istanbul");
        assert_eq!(fold("ПРИВЕТ"), "привет");
        assert_eq!(fold("日本語"), "日本語");
    }
}
