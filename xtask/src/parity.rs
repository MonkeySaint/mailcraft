//! `cargo xtask parity`: writes docs/parity.md from the engine's catalog and registry; `--check` fails when
//! the file is stale or the implemented share fell below `xtask/parity-floor.txt`.

use std::fmt::Write as _;
use std::path::Path;

use mailcraft_engine::{catalog, cmd};
use serde_json::Value;

use crate::TaskResult;

/// Lowest acceptable implemented percentage (raise it as parity improves; never lower it).
const FLOOR: &str = include_str!("../parity-floor.txt");

pub fn floor() -> Result<f64, String> {
    FLOOR
        .lines()
        .map(str::trim)
        .find(|l| !l.is_empty() && !l.starts_with('#'))
        .and_then(|l| l.parse::<f64>().ok())
        .ok_or_else(|| "xtask/parity-floor.txt must hold a percentage such as 42.5".to_owned())
}

/// Markdown table cell: pipes escaped, newlines flattened.
fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace(['\n', '\r'], " ")
}

fn pct(part: u64, whole: u64) -> String {
    if whole == 0 {
        return "–".to_owned();
    }
    let tenths = ((part as f64) * 1000.0 / (whole as f64)).round() / 10.0;
    format!("{tenths:.1}%")
}

/// The report (deterministic: no dates, sorted).
pub fn render(p: &Value, commands: usize) -> String {
    let n = |k: &str| p.get(k).and_then(Value::as_u64).unwrap_or(0);
    let (total, na, mapped, implemented) =
        (n("total_rows"), n("not_applicable"), n("mapped_rows"), n("implemented_rows"));
    let mut md = String::new();
    let _ = writeln!(md, "# Outlook parity\n");
    let _ = writeln!(
        md,
        "Generated by `cargo xtask parity` from the Outlook feature catalog (`crates/engine/catalog/*.txt`) and the \
         command registry. Do not edit by hand.\n"
    );
    let _ = writeln!(
        md,
        "**{implemented} of {mapped}** mapped Outlook features have a registered command (**{}**). The catalog \
         has {total} rows; {na} are not applicable to MailCraft. The registry has {commands} commands.\n",
        pct(implemented, mapped)
    );
    let _ = writeln!(md, "## By area\n");
    let _ = writeln!(md, "| Area | Mapped | Implemented | % | Missing |");
    let _ = writeln!(md, "|---|---:|---:|---:|---:|");
    let empty = serde_json::Map::new();
    let areas = p.get("by_area").and_then(Value::as_object).unwrap_or(&empty);
    for (area, a) in areas {
        let g = |k: &str| a.get(k).and_then(Value::as_u64).unwrap_or(0);
        let missing = a.get("missing").and_then(Value::as_array).map(Vec::len).unwrap_or(0);
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {missing} |",
            cell(area),
            g("mapped"),
            g("implemented"),
            pct(g("implemented"), g("mapped"))
        );
    }
    let missing_total = p.get("missing_ids").and_then(Value::as_array).map(Vec::len).unwrap_or(0);
    let _ = writeln!(
        md,
        "| **Total** | **{mapped}** | **{implemented}** | **{}** | **{missing_total}** |\n",
        pct(implemented, mapped)
    );
    let _ = writeln!(md, "## Missing command ids\n");
    let mut any = false;
    for (area, a) in areas {
        let ids: Vec<&str> = a
            .get("missing")
            .and_then(Value::as_array)
            .map(|v| v.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        if ids.is_empty() {
            continue;
        }
        any = true;
        let list: Vec<String> = ids.iter().map(|i| format!("`{i}`")).collect();
        let _ = writeln!(md, "- **{}** ({}): {}", cell(area), ids.len(), list.join(", "));
    }
    if !any {
        let _ = writeln!(md, "None: every mapped feature has a command.");
    }
    let _ = writeln!(md, "\n## Not applicable\n");
    let mut rows: Vec<catalog::CatalogRow> =
        catalog::catalog_rows().into_iter().filter(|r| r.id.is_none()).collect();
    rows.sort_by(|a, b| (a.area_key(), a.location, a.feature).cmp(&(b.area_key(), b.location, b.feature)));
    if rows.is_empty() {
        let _ = writeln!(md, "None.");
    } else {
        let _ = writeln!(md, "| Area | Location | Feature | Reason |");
        let _ = writeln!(md, "|---|---|---|---|");
        for r in rows {
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} |",
                cell(r.area),
                cell(r.location),
                cell(r.feature),
                cell(r.reason)
            );
        }
    }
    md
}

fn current() -> (Value, String) {
    let reg = cmd::registry();
    let p = catalog::parity(&reg);
    let md = render(&p, reg.len());
    (p, md)
}

fn summary(p: &Value) -> String {
    format!(
        "{} of {} mapped features implemented ({}%), {} not applicable, {} catalog rows",
        p.get("implemented_rows").and_then(Value::as_u64).unwrap_or(0),
        p.get("mapped_rows").and_then(Value::as_u64).unwrap_or(0),
        p.get("percent").and_then(Value::as_f64).unwrap_or(0.0),
        p.get("not_applicable").and_then(Value::as_u64).unwrap_or(0),
        p.get("total_rows").and_then(Value::as_u64).unwrap_or(0),
    )
}

pub fn write(out: &Path) -> TaskResult {
    let (p, md) = current();
    if let Some(dir) = out.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    }
    std::fs::write(out, md).map_err(|e| format!("cannot write {}: {e}", out.display()))?;
    println!("parity: {} → {}", summary(&p), out.display());
    Ok(())
}

pub fn check(out: &Path) -> TaskResult {
    let (p, md) = current();
    let floor = floor()?;
    let percent = p.get("percent").and_then(Value::as_f64).unwrap_or(0.0);
    println!("parity: {} (floor {floor}%)", summary(&p));
    if percent + 1e-9 < floor {
        return Err(format!(
            "parity fell to {percent}%, below the floor of {floor}% in xtask/parity-floor.txt"
        ));
    }
    match std::fs::read_to_string(out) {
        Ok(existing) if existing == md => Ok(()),
        Ok(_) => Err(format!("{} is stale: run `cargo xtask parity` and commit it", out.display())),
        Err(e) => Err(format!("cannot read {}: {e} (run `cargo xtask parity`)", out.display())),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn report_is_deterministic_and_complete() {
        let (p, a) = current();
        let (_, b) = current();
        assert_eq!(a, b);
        assert!(a.starts_with("# Outlook parity"));
        assert!(a.contains("| **Total** |"));
        assert!(a.contains("## Not applicable"));
        let areas = p["by_area"].as_object().unwrap().len();
        let rows =
            a.lines().filter(|l| l.starts_with("| ") && !l.starts_with("| Area") && !l.starts_with("| **"));
        assert!(rows.count() >= areas);
    }

    #[test]
    fn floor_parses_and_is_met() {
        let f = floor().unwrap();
        assert!((0.0..=100.0).contains(&f));
        let (p, _) = current();
        assert!(p["percent"].as_f64().unwrap() >= f);
    }

    #[test]
    fn check_detects_stale_files() {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("parity.md");
        assert!(check(&out).is_err());
        write(&out).unwrap();
        check(&out).unwrap();
        std::fs::write(&out, "old").unwrap();
        assert!(check(&out).unwrap_err().contains("stale"));
    }

    #[test]
    fn cells_escape_pipes() {
        assert_eq!(cell("a|b\nc"), "a\\|b c");
        assert_eq!(pct(1, 3), "33.3%");
        assert_eq!(pct(0, 0), "–");
    }
}
